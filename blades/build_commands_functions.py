#!/usr/bin/env python3
"""
Lists the Omnis commands, functions and constants a library's code uses, with
a count and the shortest real line for each -- a Markdown table to read, or
to hand an AI as "what this codebase actually writes".

Usage:  python3 build_commands_functions.py <export folder> [<label>]
                [--skip <path ending> ...] > COMMANDS_FUNCTIONS.md
        e.g.  python3 build_commands_functions.py Executor_exp/Executor "Executor 1.0.0"

<export folder> is the JSON export of the library (the folder holding its
class folders). <label> names it in the heading; default: the folder name.
--skip leaves out every method file whose path ends so; repeatable. Default:
Executor/$execute.omh -- the Executor's playground, which holds whatever
script ran last.

Full-line comments are skipped; string literals and the inline ## comment are
masked before tokens are counted.
Needs beside it: omnis_command_table.txt, omnis_constants_table.txt and
functions.txt -- all three made by build_tables.py from the Omnis help.
Commands: longest command-table entry the line starts with.
Functions: NAME( not preceded by $ . or a letter, NAME in functions.txt --
           so methods ($add, $findname ...) are NOT counted as functions.
Constants: k-tokens found in the constants table, the lower-case families
           (kcursArrow, kerrNotFound) included.
Example: the shortest real line carrying the token, cut at 160 characters.
Regenerate after the next export; never edit the output by hand.
"""
import sys, os, re, glob
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
def table(name):
    with open(os.path.join(HERE, name), encoding='utf-8', errors='replace') as fh:
        return [l.rstrip('\n\r') for l in fh if l.strip() and not l.startswith(';')]

args = sys.argv[1:]
skips = []
while '--skip' in args:
    k = args.index('--skip')
    skips.append(args[k + 1].replace('\\', '/'))
    del args[k:k + 2]
if not args:
    sys.exit(__doc__)
root = args[0]
label = args[1] if len(args) > 1 else os.path.basename(os.path.normpath(root))
skips = skips or ['Executor/$execute.omh']
# The table names some commands by their FORM ('If calculation', 'For field value');
# the keyword is what stands in the code.
FORMS = {'If calculation': 'If', 'Else If calculation': 'Else If', 'While calculation': 'While',
         'Until calculation': 'Until', 'For field value': 'For'}
commands = sorted({FORMS.get(c, c) for c in table('omnis_command_table.txt')}, key=len, reverse=True)
constants = set(table('omnis_constants_table.txt'))
functions = set(table('functions.txt'))

def mask(line):
    out, q = [], None
    i = 0
    while i < len(line):
        c = line[i]
        if q:
            out.append(' ')
            if c == q:
                if i + 1 < len(line) and line[i + 1] == q:
                    out.append(' '); i += 1
                else:
                    q = None
        elif c in "'\"":
            q = c; out.append(' ')
        elif line.startswith('##', i):
            break
        else:
            out.append(c)
        i += 1
    return ''.join(out)

cmd_n, fn_n, k_n = Counter(), Counter(), Counter()
cmd_ex, fn_ex = {}, {}
files = [f for f in glob.glob(os.path.join(root, '**', '*.omh'), recursive=True)
         if not any(f.replace('\\', '/').endswith(x) for x in skips)]
def keep(d, key, line):
    if key not in d or len(line) < len(d[key]):
        d[key] = line
for f in files:
    for raw in open(f, encoding='utf-8', errors='replace'):
        line = raw.strip().replace('\r', '')
        if not line or line.startswith('#'):
            continue
        for c in commands:
            if line == c or line.startswith(c + ' '):
                cmd_n[c] += 1; keep(cmd_ex, c, line); break
        code = mask(line)
        for m in re.finditer(r'(?<![\$\.\w])([A-Za-z_]\w*)\(', code):
            if m.group(1) in functions:
                fn_n[m.group(1)] += 1; keep(fn_ex, m.group(1), line)
        for m in re.finditer(r'\bk\w+', code):
            if m.group(0) in constants:
                k_n[m.group(0)] += 1

def cut(s):
    s = s.replace('|', '\\|')
    return s if len(s) <= 160 else s[:157] + '...'
print(f'# Commands, functions and constants used — {label}\n')
print(f'Generated by `build_commands_functions.py` from `{label}` ({len(files)} method files,')
print(f'skipped: {", ".join("`" + x + "`" for x in skips)}). '
      'Do not edit by hand — regenerate after an export.\n')
print('## Commands\n\n| n | command | shortest real line |\n|--:|---|---|')
for c, n in sorted(cmd_n.items(), key=lambda x: (-x[1], x[0])):
    print(f'| {n} | {c} | `{cut(cmd_ex[c])}` |')
print('\n## Functions\n\n| n | function | shortest real line |\n|--:|---|---|')
for c, n in sorted(fn_n.items(), key=lambda x: (-x[1], x[0])):
    print(f'| {n} | `{c}()` | `{cut(fn_ex[c])}` |')
print('\n## Constants\n')
print(', '.join(f'`{c}`({n})' for c, n in sorted(k_n.items(), key=lambda x: (-x[1], x[0]))))
